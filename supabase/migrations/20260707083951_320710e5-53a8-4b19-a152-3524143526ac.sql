CREATE TABLE public.members (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL DEFAULT 'ບໍ່ມີຊື່',
  nickname TEXT DEFAULT '',
  gender TEXT CHECK (gender IN ('M','F')) DEFAULT 'M',
  age INT DEFAULT 0,
  gen INT DEFAULT 1,
